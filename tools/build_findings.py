def layout(model, variant):
    if model == "s4nd":
        return {"2d_state": "2D (state × time)", "2d": "2D + group axis", "3d": "3D", "4d": "4D"}[variant]
    base = {"onehot": "flat one-hot", "embeddings": "flat embeddings", "cross_attention": "ASA 1-D",
            "film_attention": "FiLM", "none": "—", "numeric": "numeric"}
    if variant in base:
        return base[variant]
    dim = variant.rsplit("_", 1)[-1].upper()
    return dim if model == "mamba_nd" else f"ASA {dim}"


def label(arm):
    model, variant = arm.split("|")
    lay = layout(model, variant)
    return MODEL[model] if lay == "—" else f"{MODEL[model]} · {lay}"


def is_numeric(values):
    import re
    return all(re.fullmatch(r"[-+—]?[\d.,]*[%†]?( / [\d.]+)?|—", str(v).strip()) for v in values)


def table(df, cols, header):
    align = ["---:" if is_numeric(df[c]) else "---" for c in cols]
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(align) + "|"]
    lines += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for _, r in df.iterrows()]
    return "\n".join(lines)


